#  SECTION 10 — CONVENIENCE FUNCTIONS (used in app.py)
# ══════════════════════════════════════════════════════════════════════════════

def is_kite_connected() -> bool:
    """Returns True if Kite client is available and authenticated."""
    return get_kite_client() is not None


def get_data_source_label() -> str:
    """Returns a human-readable label for the current data source."""
    if is_kite_connected():
        return "KITE LIVE"
    return "YFINANCE"
