#  SECTION 7 — FUNDAMENTALS FROM YFINANCE  (only source for financial data)
# ══════════════════════════════════════════════════════════════════════════════

@st.cache_data(ttl=3600)   # cache for 1 hour — fundamentals don't change often
def fetch_fundamentals_yf(symbol: str) -> Dict[str, Any]:
    """
    FUNDAMENTALS SOURCE — yfinance ONLY

    Kite API does NOT provide:
      - P/E ratio, EPS, revenue, net income
      - Balance sheet, income statement, cash flow
      - Dividend yield, book value
      - Quarterly / annual earnings
      - Analyst estimates
      - Sector / industry

    This function fetches all of the above from yfinance.
    Returns the full yfinance .info dict plus structured financial tables.

    Args:
        symbol: any format — "RELIANCE", "RELIANCE.NS", "INFY.NS"
    """
    _, _, yf_sym = parse_symbol(symbol)

    try:
        import yfinance as yf
        ticker = yf.Ticker(yf_sym)
        info   = ticker.info or {}

        # Add 52W hi/lo from history if not in info
        if not info.get("fiftyTwoWeekHigh"):
            try:
                hist = ticker.history(period="1y")
                if not hist.empty:
                    info["fiftyTwoWeekHigh"] = float(hist["High"].max())
                    info["fiftyTwoWeekLow"]  = float(hist["Low"].min())
            except Exception:
                pass

        logger.info(f"yfinance fundamentals fetched for {yf_sym}: "
                    f"PE={info.get('trailingPE','N/A')} "
                    f"EPS={info.get('trailingEps','N/A')}")
        return info

    except Exception as e:
        logger.error(f"yfinance fundamentals failed for {symbol}: {e}")
        return {}


# ══════════════════════════════════════════════════════════════════════════════
#  SECTION 8 — COMBINED INFO DICT (used by app.py fetch_info)
# ══════════════════════════════════════════════════════════════════════════════

@st.cache_data(ttl=60)
def fetch_combined_info(symbol: str) -> Dict[str, Any]:
    """
    Returns a single dict combining:
      - Live price fields  →  from Kite (real-time)
      - Fundamental fields →  from yfinance (hourly cache)

    Kite price data always takes precedence over yfinance price fields.
    This dict is used throughout the TA Terminal wherever info is needed.
    """
    # Get both sources
    kite_quote  = fetch_quote_kite(symbol)
    yf_info     = fetch_fundamentals_yf(symbol)

    # Start with yfinance (fundamentals base)
    combined = dict(yf_info)

    # Override price fields with Kite live data
    price_fields = [
        "currentPrice", "regularMarketPrice", "previousClose",
        "open", "dayHigh", "dayLow", "volume",
        "regularMarketChange", "regularMarketChangePercent",
        "lastTradeTime", "averagePrice",
    ]
    for field in price_fields:
        if field in kite_quote:
            combined[field] = kite_quote[field]

    # Add source tags
    combined["_price_source"]       = kite_quote.get("source", "yfinance")
    combined["_fundamentals_source"] = "yfinance"
    combined["symbol"]               = kite_quote.get("symbol", symbol)
    combined["exchange"]             = kite_quote.get("exchange", "NSE")

    return combined


# ══════════════════════════════════════════════════════════════════════════════
#  SECTION 9 — YFINANCE FALLBACKS (price only — used when Kite unavailable)
# ══════════════════════════════════════════════════════════════════════════════

def _yf_ohlcv(symbol: str, timeframe: str, period: str) -> pd.DataFrame:
    """yfinance OHLCV fallback — only used when Kite unavailable."""
    try:
        import yfinance as yf
        _, _, yf_sym = parse_symbol(symbol)
        interval = TF_TO_YF_INTERVAL.get(timeframe, "1d")
        ticker = yf.Ticker(yf_sym)
        df = ticker.history(period=period, interval=interval, auto_adjust=True)
        if df.empty:
            return pd.DataFrame()
        df.index = pd.to_datetime(df.index)
        if hasattr(df.index, "tz") and df.index.tz is not None:
            df.index = df.index.tz_localize(None)
        df = df[["Open", "High", "Low", "Close", "Volume"]].dropna()
        logger.info(f"yfinance OHLCV fallback: {yf_sym} → {len(df)} bars")
        return df
    except Exception as e:
        logger.error(f"yfinance OHLCV fallback failed: {e}")
        return pd.DataFrame()


def _yf_quote(symbol: str) -> Dict[str, Any]:
    """yfinance quote fallback — only used when Kite quote fails."""
    try:
        import yfinance as yf
        _, _, yf_sym = parse_symbol(symbol)
        info = yf.Ticker(yf_sym).info or {}
        ltp  = info.get("currentPrice") or info.get("regularMarketPrice", 0)
        prev = info.get("previousClose", 0)
        chg  = ltp - prev
        return {
            "symbol":                     symbol,
            "exchange":                   "NSE",
            "currentPrice":               ltp,
            "regularMarketPrice":         ltp,
            "previousClose":              prev,
            "open":                       info.get("open",    0),
            "dayHigh":                    info.get("dayHigh", 0),
            "dayLow":                     info.get("dayLow",  0),
            "volume":                     info.get("volume",  0),
            "regularMarketChange":        round(chg, 2),
            "regularMarketChangePercent": round(chg / prev * 100, 4) if prev else 0,
            "source":                     "yfinance",
        }
    except Exception:
        return {"currentPrice": 0, "source": "error"}


