#  kite_data.py  —  Unified Data Layer for TA Terminal  v3.0
#
#  RULE:
#    ALL price / OHLCV / quote data  →  Zerodha Kite API
#    ALL fundamental / financial data →  yfinance (no Kite equivalent)
#
#  Returns DataFrames in the EXACT same format the TA modules expect:
#    Columns : Open, High, Low, Close, Volume  (capital first letter)
#    Index   : DatetimeIndex, timezone-naive
