@st.cache_data(ttl=300)
def fetch_multi_tf_kite(symbol: str,
                         period: str = "1y") -> Dict[str, pd.DataFrame]:
    """
    Fetches OHLCV for all 4 timeframes used in Multi-Timeframe Analysis.
    All data from Kite (falls back per-timeframe to yfinance if needed).

    Returns:
        {
          "monthly" : DataFrame,
          "weekly"  : DataFrame,
          "daily"   : DataFrame,
          "h4"      : DataFrame,  # 60min bars as 4H proxy
        }
    """
    result = {}
    tf_map = [
        ("monthly", "Monthly", "5y"),
        ("weekly",  "Weekly",  "2y"),
        ("daily",   "Daily",   period),
        ("h4",      "4H",      "6mo"),
    ]
    for key, tf_label, tf_period in tf_map:
        try:
            df = fetch_ohlcv_kite(symbol, timeframe=tf_label, period=tf_period)
            if not df.empty:
                result[key] = df
                logger.info(f"MTF {key}: {len(df)} bars")
        except Exception as e:
            logger.warning(f"MTF fetch failed {symbol} {tf_label}: {e}")

    return result


